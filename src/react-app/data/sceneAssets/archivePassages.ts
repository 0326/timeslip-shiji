/**
 * 从 ARCHIVE_BIOS 的 bio 文本自动生成简化的生平历程。
 * 用于兜底：当该人物既无远程 passages 又无本地手写 ARCHIVE_PASSAGES 时启用。
 * 将 bio 按句号拆分生成 1~3 条简单事件。
 */
import { ARCHIVE_BIOS } from "./archiveBios";

export function getPassagesFor(figureId: string): PassageWithRelations[] {
	// 1) 本地手写优先
	const local = ARCHIVE_PASSAGES[figureId];
	if (local && local.length > 0) return local;

	// 2) 从 bio 拆分兜底（给未手写的约 180+ 角色一条简单时间线）
	const bio = ARCHIVE_BIOS[figureId] || "";
	if (!bio) return [];

	// 按句号、问号拆分，过滤掉过短的碎片
	const sentences = bio
		.split(/[。？！]/)
		.map((s) => s.trim())
		.filter((s) => s.length >= 4)
		.slice(0, 6);

	if (sentences.length === 0) return [];

	return sentences.map((sentence, i) =>
		mk(
			figureId,
			`${figureId}-auto-${i}`,
			"auto",
			"本传",
			0,
			`生平·${i + 1}`,
			sentence + "。",
			null,
			null,
			i + 1,
			[],
			"",
		),
	);
}

/**
 * 汇总人物关系图（思维导图用）。
 * 扫描 ARCHIVE_PASSAGES 的 related_ids + event_group，构建 nodes/links。
 * 以 focusId 为中心，半径 1 层的 egonet。
 */
export interface GraphNode {
	id: string;
	name: string;
	dynasty: string;
	identity: string;
	isFocus?: boolean;
}
export interface GraphLink {
	source: string;
	target: string;
	type: "event" | "coworker";
	label?: string;
}
export interface MindMapGraph {
	nodes: GraphNode[];
	links: GraphLink[];
	eventGroups: string[];
}

import { SPRITE_DYNASTY_MAP, SPRITES } from "./index";
import { SPRITE_IDENTITY_MAP } from "./archiveIdentities";

// 名字解析：SPRITES 注册表优先 → bio 首句兜底
function guessName(id: string): string {
	const sp = SPRITES[id];
	if (sp?.name) return sp.name;
	const bio = ARCHIVE_BIOS[id] || "";
	const m = bio.match(/^([^，。]{1,10})[，。]/);
	if (m) return m[1];
	return id;
}

// ── 预计算双向索引（仅扫描手写 ARCHIVE_PASSAGES，自动生成的无 related_ids）──
interface IndexedPassage {
	ownerId: string;
	passage: PassageWithRelations;
}
/** 被提及人物 id → 所有在 related_ids 中提到它的 passage */
const INDEX_BY_RELATED: Map<string, IndexedPassage[]> = new Map();
/** event_group → 该事件下所有 passage */
const INDEX_BY_EVENT: Map<string, IndexedPassage[]> = new Map();

(function buildIndexes() {
	for (const [ownerId, passages] of Object.entries(ARCHIVE_PASSAGES)) {
		for (const passage of passages) {
			const entry: IndexedPassage = { ownerId, passage };
			for (const rid of passage.related_ids || []) {
				if (!INDEX_BY_RELATED.has(rid))
					INDEX_BY_RELATED.set(rid, []);
				INDEX_BY_RELATED.get(rid)!.push(entry);
			}
			if (passage.event_group) {
				if (!INDEX_BY_EVENT.has(passage.event_group))
					INDEX_BY_EVENT.set(passage.event_group, []);
				INDEX_BY_EVENT.get(passage.event_group)!.push(entry);
			}
		}
	}
})();

export function buildMindMapGraph(focusId: string): MindMapGraph {
	const nodes = new Map<string, GraphNode>();
	const links: GraphLink[] = [];
	const events = new Set<string>();
	const linkSet = new Set<string>(); // "a|b" 去重

	const addNode = (id: string, isFocus = false) => {
		if (!nodes.has(id)) {
			nodes.set(id, {
				id,
				name: guessName(id),
				dynasty: SPRITE_DYNASTY_MAP[id] || "",
				identity: SPRITE_IDENTITY_MAP[id] || "文人",
				isFocus,
			});
		}
	};
	const addLink = (a: string, b: string, type: "event" | "coworker", label?: string) => {
		if (a === b) return;
		const key = a < b ? `${a}|${b}` : `${b}|${a}`;
		if (linkSet.has(key)) return;
		linkSet.add(key);
		links.push({ source: a, target: b, type, label });
	};

	addNode(focusId, true);

	// ── 收集与 focusId 相关的所有 passage（正反双向 + 同事件）──
	const relevantPassages = new Map<string, IndexedPassage>(); // key = ownerId:passage_id

	// 1) focusId 自己的 passage
	for (const p of getPassagesFor(focusId)) {
		relevantPassages.set(`${focusId}:${p.passage_id}`, { ownerId: focusId, passage: p });
	}
	// 2) 其他人物的 passage 中，related_ids 包含 focusId 的（反向发现）
	for (const entry of INDEX_BY_RELATED.get(focusId) || []) {
		relevantPassages.set(`${entry.ownerId}:${entry.passage.passage_id}`, entry);
	}

	// ── 从相关 passage 中提取事件组 ──
	for (const { passage } of relevantPassages.values()) {
		if (passage.event_group) events.add(passage.event_group);
	}

	// 3) 同事件组补充：focusId 参与的事件组里的其他 passage（即使没直接提 focusId）
	for (const eventGroup of events) {
		for (const entry of INDEX_BY_EVENT.get(eventGroup) || []) {
			relevantPassages.set(`${entry.ownerId}:${entry.passage.passage_id}`, entry);
		}
	}

	// ── 遍历所有相关 passage，建节点和连线 ──
	for (const { ownerId, passage } of relevantPassages.values()) {
		addNode(ownerId);
		const rels = (passage.related_ids || []).filter((r) => r !== ownerId);
		// owner → 每个 related
		for (const relId of rels) {
			addNode(relId);
			addLink(ownerId, relId, passage.event_group ? "event" : "coworker", passage.event_group || passage.title);
		}
		// 同 passage 内 related_ids 之间互联（同事件共现）
		if (rels.length >= 2) {
			for (let i = 0; i < rels.length; i++) {
				for (let j = i + 1; j < rels.length; j++) {
					addLink(rels[i], rels[j], "event", passage.event_group || passage.title);
				}
			}
		}
	}

	return {
		nodes: Array.from(nodes.values()),
		links,
		eventGroups: Array.from(events),
	};
}
